-- docs/SPENT_CASE_RESEARCH.md: what each spent-case policy would do to the
-- brass economy. ANALYSIS ONLY: no spent-case item, recipe or hook exists.
-- The policies and their numbers are the parameters of this calculation,
-- not data of the mod; they are here so that the decision can be made on
-- figures that follow the calibre model when it changes.
--
--   factory, handloaded  share of fired rounds of that origin that leave a
--                        spent case the player ends up holding
--   scrap                share of a spent case's brass that comes back when
--                        it is scrapped (unused components return 0.5)
--   resize               reloadable cases per spent case (0: cannot be
--                        resized); factoryResize for factory brass
------------------------------------------------

B.SPENT_POLICIES = {
    { id = "A", label = "every fired round leaves a clean case", factory = 1, handloaded = 1, scrap = 0.5, resize = 1, factoryResize = 1 },
    { id = "B", label = "factory cases are poor scrap and cannot be reloaded", factory = 1, handloaded = 1, scrap = 0.25, resize = 0.75, factoryResize = 0 },
    { id = "C", label = "only handloaded rounds leave a case", factory = 0, handloaded = 1, scrap = 0.25, resize = 0.75, factoryResize = 0 },
    { id = "D", label = "every round leaves a case; half are lost, the rest are dirty", factory = 0.5, handloaded = 0.5, scrap = 0.25, resize = 0.75, factoryResize = 0.75 },
    { id = "E", label = "no spent cases", factory = 0, handloaded = 0, scrap = 0, resize = 0, factoryResize = 0 },
}

B.SPENT_CALIBRES = { "9mm", ".308", "12 Gauge" }

-- rounds of one origin ("factory" or "handloaded") fired under a policy.
function B.spentCases(policy, calibre, rounds, origin)
    local C = AC_Calibres.CONFIG
    local perIngot = AC_Materials.CONFIG.unitsPerIngot
    local caseUnits = C.cupUnits * calibre.cupsPerCase
    local primer = AC_Calibres.getPrimer(calibre.primerFamily)
    local s = {}
    s.cases = rounds * policy[origin]
    -- Scrapped and recast.
    s.scrapIngots = s.cases * caseUnits * policy.scrap / perIngot
    -- Resized into cases for new rounds: how many, and the brass they
    -- would otherwise have had to be drawn from.
    local resize = origin == "factory" and policy.factoryResize or policy.resize
    s.reloadable = s.cases * resize
    s.reloadIngots = s.reloadable * caseUnits / perIngot
    -- What a hundred new rounds would still need in brass if the
    -- reloadable cases went into them: every primer, and the cases short.
    local short = math.max(0, rounds - s.reloadable)
    s.brassNeeded = (short * caseUnits + rounds * primer.brassUnits) / perIngot
    s.brassFromScratch = rounds * (caseUnits + primer.brassUnits) / perIngot
    -- Ore: brass is ore one for one; the projectiles' copper is unchanged.
    s.oreFromScratch = s.brassFromScratch + rounds / calibre.bulletsPerScrap * C.scrapUnits / perIngot
    s.oreNeeded = s.oreFromScratch - (s.brassFromScratch - s.brassNeeded)
    return s
end

B.SPENT_START = "<!-- SPENT CASE POLICY TABLE: generated by tests/write_recipes.lua from the calibre model. Do not edit. -->"
B.SPENT_FINISH = "<!-- END SPENT CASE POLICY TABLE -->"

function B.renderSpentPolicies()
    local header = { "Policy" }
    local rule = { "---" }
    for _, id in ipairs(B.SPENT_CALIBRES) do
        table.insert(header, "100 looted " .. id .. ": cases, ingots if scrapped, ingots' worth if reloaded")
        table.insert(rule, "---")
    end
    local looted = {
        "| " .. table.concat(header, " | ") .. " |",
        "|" .. table.concat(rule, "|") .. "|",
    }
    for _, policy in ipairs(B.SPENT_POLICIES) do
        local cells = { "**" .. policy.id .. "**: " .. policy.label }
        for _, id in ipairs(B.SPENT_CALIBRES) do
            local s = B.spentCases(policy, AC_Calibres.get(id), 100, "factory")
            table.insert(cells, short(s.cases) .. ", " .. short(s.scrapIngots) .. ", " .. short(s.reloadIngots))
        end
        table.insert(looted, "| " .. table.concat(cells, " | ") .. " |")
    end

    header = { "Policy" }
    rule = { "---" }
    for _, id in ipairs(B.SPENT_CALIBRES) do
        table.insert(header, "the next 100 " .. id .. ": cases back, brass ingots still needed (of), ore (of)")
        table.insert(rule, "---")
    end
    local loop = {
        "| " .. table.concat(header, " | ") .. " |",
        "|" .. table.concat(rule, "|") .. "|",
    }
    for _, policy in ipairs(B.SPENT_POLICIES) do
        local cells = { "**" .. policy.id .. "**" }
        for _, id in ipairs(B.SPENT_CALIBRES) do
            local s = B.spentCases(policy, AC_Calibres.get(id), 100, "handloaded")
            table.insert(cells, short(s.reloadable) .. ", " .. short(s.brassNeeded) .. " (" .. short(s.brassFromScratch) .. "), " .. short(s.oreNeeded) .. " (" .. short(s.oreFromScratch) .. ")")
        end
        table.insert(loop, "| " .. table.concat(cells, " | ") .. " |")
    end
    return "Looted factory ammunition as a source of brass, per hundred rounds fired:\n\n" .. table.concat(looted, "\n")
        .. "\n\nThe player's own rounds, fired and reloaded: what the next hundred cost:\n\n" .. table.concat(loop, "\n")
end

function B.renderSpentBlock()
    return B.SPENT_START .. "\n\n" .. B.renderSpentPolicies() .. "\n\n" .. B.SPENT_FINISH
end

function B.replaceSpent(text)
    return replaceBetween(text, B.SPENT_START, B.SPENT_FINISH, B.renderSpentBlock())
end

