-- docs/LOOT_AND_RECYCLING.md: where a die set can be found. Rendered from
-- AC_Loot, with each list's roll count from the vanilla snapshot.
------------------------------------------------

B.LOOT_START = "<!-- LOOT TABLE: generated by tests/write_recipes.lua from AC_Loot.lua. Do not edit. -->"
B.LOOT_FINISH = "<!-- END LOOT TABLE -->"

local function percent(value)
    return string.format("%.2f %%", value)
end

-- vanilla: the table tests/vanilla_snapshot.lua returns.
function B.renderLoot(vanilla)
    local lines = {
        "| Loot list | Filled from it | Die sets | Weight each | Chance per container, each | Chance per container, any die set |",
        "|---|---|---|---|---|---|",
    }
    for _, target in ipairs(AC_Loot.TARGETS) do
        local rolls = vanilla.loot.lists[target.list].rolls
        local names, weights, chances, total = {}, {}, {}, 0
        local seen = {}
        for _, entry in ipairs(AC_Loot.buildEntries({ target })) do
            table.insert(names, entry.calibre)
            total = total + entry.weight
            if not seen[entry.weight] then
                seen[entry.weight] = true
                table.insert(weights, tostring(entry.weight))
                table.insert(chances, percent(AC_Loot.chancePerContainer(entry.weight, rolls)))
            end
        end
        table.insert(lines, "| " .. table.concat({
            "`" .. target.list .. "`",
            target.where,
            table.concat(names, ", "),
            table.concat(weights, " / "),
            table.concat(chances, " / "),
            percent(AC_Loot.chancePerContainer(total, rolls)),
        }, " | ") .. " |")
    end

    local tiers = {
        "| Die set | Tier | Lists |",
        "|---|---|---|",
    }
    local entries = AC_Loot.buildEntries()
    for _, calibre in ipairs(AC_Calibres.LIST) do
        local lists = {}
        for _, entry in ipairs(entries) do
            if entry.item == calibre.dieSet then table.insert(lists, "`" .. entry.list .. "` " .. entry.weight) end
        end
        table.insert(tiers, "| " .. calibre.id .. " | " .. tostring(calibre.lootTier) .. " | " .. table.concat(lists, ", ") .. " |")
    end
    return table.concat(lines, "\n") .. "\n\n" .. table.concat(tiers, "\n")
end

function B.renderLootBlock(vanilla)
    return B.LOOT_START .. "\n\n" .. B.renderLoot(vanilla) .. "\n\n" .. B.LOOT_FINISH
end

function B.replaceLoot(text, vanilla)
    return replaceBetween(text, B.LOOT_START, B.LOOT_FINISH, B.renderLootBlock(vanilla))
end

