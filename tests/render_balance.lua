B.AUDIT_START = "<!-- RECIPE AUDIT TABLE: generated by tests/write_recipes.lua from AC_Materials.RECIPES. Do not edit. -->"
B.AUDIT_FINISH = "<!-- END RECIPE AUDIT TABLE -->"

local FAMILIES = {
    { "metallurgy", "Metallurgy (ore to brass)" },
    { "caseStock", "Case stock (sheets, cups)" },
    { "powder", "Gunpowder" },
    { "primer", "Primers" },
    { "dieSet", "Die sets" },
    { "case", "Cases and hulls" },
    { "bullet", "Bullets and shot" },
    { "assemble", "Assembly" },
    { "scrap", "Scrapping brass" },
    { "recast", "Recasting brass scrap" },
}

function B.recipeFamily(recipe)
    if recipe.step then return recipe.step end
    if recipe.benchTag == "PrimitiveFurnace" or recipe.benchTag == "Furnace" then return "metallurgy" end
    return "caseStock"
end

-- "5", or "1 to 3".
local function range(low, high)
    if low == high then return tostring(low) end
    return low .. " to " .. high
end

function B.renderRecipeAudit()
    local lines = {
        "| Family | Recipes | Station tags | Ammo Making level | XP per craft | Time | Kept tools | Consumed lines | Output lines |",
        "|---|---|---|---|---|---|---|---|---|",
    }
    local total = 0
    for _, family in ipairs(FAMILIES) do
        local count, stations, seen = 0, {}, {}
        local level, xp, time, kept, consumed, outputs = {}, {}, {}, {}, {}, {}
        local function note(bucket, value)
            bucket.low = math.min(bucket.low or value, value)
            bucket.high = math.max(bucket.high or value, value)
        end
        for _, recipe in ipairs(AC_Materials.RECIPES) do
            if B.recipeFamily(recipe) == family[1] then
                count = count + 1
                if not seen[recipe.benchTag] then
                    seen[recipe.benchTag] = true
                    table.insert(stations, "`" .. recipe.benchTag .. "`")
                end
                note(level, AC_Materials.getRequiredLevel(recipe))
                note(xp, AC_Materials.getRecipeXP(recipe))
                note(time, recipe.time)
                local keptLines, consumedLines = 0, 0
                for _, input in ipairs(recipe.inputs) do
                    if input.keep then keptLines = keptLines + 1 else consumedLines = consumedLines + 1 end
                end
                note(kept, keptLines)
                note(consumed, consumedLines)
                note(outputs, #recipe.outputs)
            end
        end
        total = total + count
        table.insert(lines, "| " .. table.concat({
            family[2], tostring(count), table.concat(stations, ", "),
            range(level.low, level.high), range(xp.low, xp.high), range(time.low, time.high),
            range(kept.low, kept.high), range(consumed.low, consumed.high), range(outputs.low, outputs.high),
        }, " | ") .. " |")
    end
    table.insert(lines, "| **All** | **" .. total .. "** | | | | | | | |")
    return table.concat(lines, "\n")
end

function B.renderRecipeAuditBlock()
    return B.AUDIT_START .. "\n\n" .. B.renderRecipeAudit() .. "\n\n" .. B.AUDIT_FINISH
end

function B.replaceRecipeAudit(text)
    return replaceBetween(text, B.AUDIT_START, B.AUDIT_FINISH, B.renderRecipeAuditBlock())
end

