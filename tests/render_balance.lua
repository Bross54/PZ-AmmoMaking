-- README.md carries a shorter table of the same model, for players.
------------------------------------------------

B.SUMMARY_START = "<!-- CALIBRE TABLE: generated by tests/write_recipes.lua from AC_Calibres.lua. Do not edit. -->"
B.SUMMARY_FINISH = "<!-- END CALIBRE TABLE -->"

-- "SmallPistol" -> "small pistol"
local function spaced(name)
    return string.lower((string.gsub(name, "(%l)(%u)", "%1 %2")))
end

function B.renderSummary()
    local C = AC_Calibres.CONFIG
    local lines = {
        "| Round | Type | Vanilla item | Primer | Cups per case | Projectiles per scrap | Powder charges | Wads | Round at level | Ore per 100 rounds |",
        "|---|---|---|---|---|---|---|---|---|---|",
    }
    for _, calibre in ipairs(AC_Calibres.LIST) do
        local primer = AC_Calibres.getPrimer(calibre.primerFamily)
        local brass = calibre.cupsPerCase * C.cupUnits + primer.brassUnits
        table.insert(lines, "| " .. table.concat({
            calibre.id,
            calibre.class,
            "`" .. calibre.round .. "`",
            spaced(calibre.primerFamily),
            tostring(calibre.cupsPerCase),
            tostring(calibre.bulletsPerScrap),
            tostring(calibre.powderUses),
            tostring(calibre.wads),
            tostring(calibre.levels.assemble),
            tostring(100 * brass / AC_Materials.CONFIG.unitsPerIngot + 100 / calibre.bulletsPerScrap / 10),
        }, " | ") .. " |")
    end
    return table.concat(lines, "\n")
end

function B.renderSummaryBlock()
    return B.SUMMARY_START .. "\n\n" .. B.renderSummary() .. "\n\n" .. B.SUMMARY_FINISH
end

function B.replaceSummary(text)
    return replaceBetween(text, B.SUMMARY_START, B.SUMMARY_FINISH, B.renderSummaryBlock())
end

return B
