B.RECYCLING_START = "<!-- RECYCLING TABLE: generated by tests/write_recipes.lua from AC_Recycling.lua. Do not edit. -->"
B.RECYCLING_FINISH = "<!-- END RECYCLING TABLE -->"

function B.renderRecycling()
    local scrapUnits = AC_Materials.UNITS[AC_Recycling.CONFIG.scrapItem].units
    local lines = {
        "| Recipe | Takes (any mix of) | Per craft | Brass in | Brass scrap out | Brass out | Lost | Level | XP |",
        "|---|---|---|---|---|---|---|---|---|",
    }
    for _, group in ipairs(AC_Recycling.buildGroups()) do
        local items = {}
        for _, itemType in ipairs(group.items) do table.insert(items, "`" .. itemType .. "`") end
        local brassIn, brassOut = group.count * group.units, group.scrap * scrapUnits
        table.insert(lines, "| " .. table.concat({
            "`" .. AC_Recycling.CONFIG.idPrefix .. group.units .. "`",
            table.concat(items, ", "),
            tostring(group.count),
            tostring(brassIn),
            tostring(group.scrap),
            tostring(brassOut),
            tostring(brassIn - brassOut),
            tostring(AC_Recycling.CONFIG.requiredLevel),
            tostring(AC_Recycling.CONFIG.xp),
        }, " | ") .. " |")
    end
    local C = AC_Recycling.CONFIG
    table.insert(lines, "| " .. table.concat({
        "`" .. C.castId .. "`",
        "`" .. C.scrapItem .. "`",
        tostring(C.scrapPerIngot),
        tostring(C.scrapPerIngot * scrapUnits),
        "1 `" .. C.ingotItem .. "`",
        tostring(C.ingotUnits),
        tostring(C.scrapPerIngot * scrapUnits - C.ingotUnits),
        tostring(C.requiredLevel),
        tostring(C.xp),
    }, " | ") .. " |")
    return table.concat(lines, "\n")
end

function B.renderRecyclingBlock()
    return B.RECYCLING_START .. "\n\n" .. B.renderRecycling() .. "\n\n" .. B.RECYCLING_FINISH
end

function B.replaceRecycling(text)
    return replaceBetween(text, B.RECYCLING_START, B.RECYCLING_FINISH, B.renderRecyclingBlock())
end

